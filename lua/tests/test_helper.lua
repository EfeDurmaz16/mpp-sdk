function M.run()
  local passed = 0
  local failed = 0
  local skipped = 0
  -- Force unbuffered stdout so the test runner's progress shows up
  -- immediately under luacov or when output is captured to a file.
  io.stdout:setvbuf('no')
  for i = 1, #M.tests do
    local entry = M.tests[i]
    if SKIP[entry.name] then
      skipped = skipped + 1
      io.stdout:write('skip - ' .. entry.name .. '\n')
    else
      local ok, err = pcall(entry.fn)
      if not ok then
        failed = failed + 1
        io.stderr:write('FAIL ' .. entry.name .. '\n')
        io.stderr:write(tostring(err) .. '\n')
      else
        passed = passed + 1
        io.stdout:write('ok - ' .. entry.name .. '\n')
      end
    end
  end
  io.stdout:write(string.format('%d tests passed, %d skipped, %d failed\n', passed, skipped, failed))
  if failed > 0 then
    os.exit(1)
  end
end

return M
